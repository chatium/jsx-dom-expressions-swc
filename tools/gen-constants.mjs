// Regenerates src/constants.rs from the upstream sources, so the lists cannot drift by transcription.
// Usage: node tools/gen-constants.mjs <dom-expressions checkout at the pinned commit>
import fs from 'node:fs'
import path from 'node:path'

const repo = process.argv[2]
const P = path.join(repo, 'packages/babel-plugin-jsx-dom-expressions/src')
const c = await import(path.join(repo, 'packages/dom-expressions/src/constants.js'))

const arr = s => [...s.matchAll(/"([^"]*)"/g)].map(m => m[1])
const void_ = arr(fs.readFileSync(P + '/VoidElements.js', 'utf8').replace(/'/g, '"'))
const dc = fs.readFileSync(P + '/dom/constants.js', 'utf8')
const inline = arr(dc.slice(dc.indexOf('InlineElements'), dc.indexOf('BlockElements')))
const block = arr(dc.slice(dc.indexOf('BlockElements')))
const el = fs.readFileSync(P + '/dom/element.js', 'utf8')
const always = arr(el.slice(el.indexOf('const alwaysClose'), el.indexOf('export function transformElement')))

const set = (n, v) =>
  `pub(crate) static ${n}: &[&str] = &[\n${[...v].map(s => '    ' + JSON.stringify(s) + ',').join('\n')}\n];\n\n`
const pairs = (n, o) =>
  `pub(crate) static ${n}: &[(&str, &str)] = &[\n${Object.entries(o)
    .map(([k, v]) => `    (${JSON.stringify(k)}, ${JSON.stringify(v)}),`)
    .join('\n')}\n];\n\n`

let out = '// Generated by tools/gen-constants.mjs from dom-expressions — do not edit by hand.\n\n'
out += set('PROPERTIES', c.Properties)
out += set('CHILD_PROPERTIES', c.ChildProperties)
out += set('DELEGATED_EVENTS', c.DelegatedEvents)
out += set('SVG_ELEMENTS', c.SVGElements)
out += set('VOID_ELEMENTS', void_)
out += set('INLINE_ELEMENTS', inline)
out += set('BLOCK_ELEMENTS', block)
out += set('ALWAYS_CLOSE', always)
out += pairs('ALIASES', c.Aliases)
out += pairs('SVG_NAMESPACE', c.SVGNamespace)
out += fs.readFileSync(path.join(import.meta.dirname, 'constants-tail.rs'), 'utf8')
fs.writeFileSync(path.join(import.meta.dirname, '..', 'src', 'constants.rs'), out)
console.log('src/constants.rs written')

// validate-html-nesting's tables, emitted as sorted slices for binary search.
const nesting = await import('validate-html-nesting/src/mapping.js').catch(() =>
  import(path.join(import.meta.dirname, 'node_modules/validate-html-nesting/src/mapping.js')),
)
const table = (name, map) => {
  const entries = Object.entries(map.default ?? map).sort(([a], [b]) => (a < b ? -1 : 1))
  return (
    `pub(crate) static ${name}: &[(&str, &[&str])] = &[\n` +
    entries
      .map(([key, set]) => {
        const values = [...set].sort()
        return `    (${JSON.stringify(key)}, &[${values.map(v => JSON.stringify(v)).join(', ')}]),`
      })
      .join('\n') +
    '\n];\n\n'
  )
}
const m = nesting.default ?? nesting
let nestingOut = '// Generated by tools/gen-constants.mjs from validate-html-nesting — do not edit by hand.\n\n'
nestingOut += table('ONLY_VALID_CHILDREN', m.onlyValidChildren)
nestingOut += table('ONLY_VALID_PARENTS', m.onlyValidParents)
nestingOut += table('KNOWN_INVALID_CHILDREN', m.knownInvalidChildren)
nestingOut += table('KNOWN_INVALID_PARENTS', m.knownInvalidParents)
nestingOut += fs.readFileSync(path.join(import.meta.dirname, 'nesting-tail.rs'), 'utf8')
fs.writeFileSync(path.join(import.meta.dirname, '..', 'src', 'nesting.rs'), nestingOut)
console.log('src/nesting.rs written')
